class Solution {
public:
    int numberOfWays(int n, int x) {
        const int MOD = 1e9+7;
        vector<long long> dp(n+1);
        dp[0]=1;
        for(int i=1;;i++)
        {
            long long val=1;
            for(int j=1;j<=x;j++)
            {
                val*=i;
            }
            if(val>n)
            {
                break;
            }
            for(int c=n;c>=val;c--)
            {
                dp[c]=(dp[c]+dp[c-val])%(MOD);
            }
        }
        return dp[n];
    }
};

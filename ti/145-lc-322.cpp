class Solution {
public:
    int coinChange(vector<int>& coins, int amount) {
        int n=coins.size();
        vector memo(2,vector<int>(amount+1,INT_MAX/2));
        memo[0][0]=0;
        for(int i=0;i<n;i++)
        {
            for(int c=0;c<=amount;c++)
            {
                if(c<coins[i])
                {
                    memo[(i+1)%2][c]=memo[i%2][c];
                }else
                {
                    memo[(i+1)%2][c]=min(memo[i%2][c],memo[(i+1)%2][c-coins[i]]+1);
                }
            }
        }
        int ans=memo[n%2][amount];
        return ans<INT_MAX/2?ans:-1;
    }
};

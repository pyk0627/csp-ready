class Solution {
public:
    int deleteAndEarn(vector<int>& nums) {
        int maxVal = *max_element(nums.begin(), nums.end());
        vector<int> sum(maxVal + 1, 0);
        
        // 统计每个值的总点数
        for (int x : nums) {
            sum[x] += x;
        }
        
        // 打家劫舍 DP
        int prev2 = 0, prev1 = 0;
        for (int i = 1; i <= maxVal; i++) {
            int cur = max(prev1, prev2 + sum[i]);
            prev2 = prev1;
            prev1 = cur;
        }
        return prev1;
    }
};
